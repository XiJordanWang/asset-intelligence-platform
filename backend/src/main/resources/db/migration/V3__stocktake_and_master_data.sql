-- Stocktake: a campaign fans out to one task per site; each task holds the assets to count.
CREATE TABLE stocktake_campaign (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference       VARCHAR(32)  NOT NULL UNIQUE,
    title           VARCHAR(200) NOT NULL,
    scope_plant     VARCHAR(16),
    scope_category  VARCHAR(32),
    sample_percent  INT          NOT NULL,
    photo_required  BOOLEAN      NOT NULL,
    status          VARCHAR(16)  NOT NULL,
    due_date        DATE         NOT NULL,
    created_by      VARCHAR(80)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    started_at      TIMESTAMP,
    completed_at    TIMESTAMP,
    version         BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE stocktake_task (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   BIGINT      NOT NULL REFERENCES stocktake_campaign (id),
    site_id       BIGINT      NOT NULL REFERENCES site (id),
    coordinator   VARCHAR(80) NOT NULL,
    status        VARCHAR(16) NOT NULL,
    submitted_at  TIMESTAMP
);

CREATE INDEX idx_stocktake_task_campaign ON stocktake_task (campaign_id);

CREATE TABLE stocktake_line (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT       NOT NULL REFERENCES stocktake_task (id),
    asset_id    BIGINT       NOT NULL REFERENCES asset (id),
    result      VARCHAR(16)  NOT NULL,
    note        VARCHAR(500),
    counted_by  VARCHAR(80),
    counted_at  TIMESTAMP
);

CREATE INDEX idx_stocktake_line_task ON stocktake_line (task_id);
