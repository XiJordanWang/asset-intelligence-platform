-- Fictional NZ manufacturing company: plants, sites, assets and investment requests.

CREATE TABLE site (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(16)  NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    plant_code    VARCHAR(16)  NOT NULL,
    city          VARCHAR(80)  NOT NULL,
    region        VARCHAR(80)  NOT NULL,
    latitude      DOUBLE PRECISION NOT NULL,
    longitude     DOUBLE PRECISION NOT NULL,
    annual_capex_budget NUMERIC(19, 2) NOT NULL
);

CREATE TABLE asset (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag                VARCHAR(32)  NOT NULL UNIQUE,
    name               VARCHAR(200) NOT NULL,
    category           VARCHAR(32)  NOT NULL,
    status             VARCHAR(32)  NOT NULL,
    site_id            BIGINT       NOT NULL REFERENCES site (id),
    supplier           VARCHAR(120),
    original_value     NUMERIC(19, 2) NOT NULL,
    impairment         NUMERIC(19, 2) NOT NULL DEFAULT 0,
    in_service_date    DATE,
    last_verified_date DATE
);

CREATE INDEX idx_asset_site ON asset (site_id);
CREATE INDEX idx_asset_category ON asset (category);

CREATE TABLE investment_request (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        VARCHAR(32)  NOT NULL UNIQUE,
    title            VARCHAR(200) NOT NULL,
    justification    VARCHAR(4000),
    category         VARCHAR(32)  NOT NULL,
    amount           NUMERIC(19, 2) NOT NULL,
    site_id          BIGINT       NOT NULL REFERENCES site (id),
    requested_by     VARCHAR(80)  NOT NULL,
    status           VARCHAR(32)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL,
    capitalised_asset_id BIGINT REFERENCES asset (id)
);

CREATE TABLE approval_step (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    BIGINT      NOT NULL REFERENCES investment_request (id),
    step_order    INT         NOT NULL,
    approver_role VARCHAR(32) NOT NULL,
    decision      VARCHAR(16) NOT NULL,
    decided_by    VARCHAR(80),
    comment       VARCHAR(1000),
    decided_at    TIMESTAMP
);

CREATE INDEX idx_step_request ON approval_step (request_id);
