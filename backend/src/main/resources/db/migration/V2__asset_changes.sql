-- Asset lock, retirement date and optimistic locking.
ALTER TABLE asset ADD COLUMN locked_by_change VARCHAR(32);
ALTER TABLE asset ADD COLUMN disposed_date DATE;
ALTER TABLE asset ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

-- Generic change request for existing assets (transfer, disposal). One handler per type.
CREATE TABLE asset_change (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        VARCHAR(32)  NOT NULL UNIQUE,
    change_type      VARCHAR(32)  NOT NULL,
    asset_id         BIGINT       NOT NULL REFERENCES asset (id),
    requested_by     VARCHAR(80)  NOT NULL,
    reason           VARCHAR(1000),
    status           VARCHAR(32)  NOT NULL,
    target_site_id   BIGINT REFERENCES site (id),
    disposal_reason  VARCHAR(32),
    net_book_value   NUMERIC(19, 2),
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL,
    version          BIGINT       NOT NULL DEFAULT 0
);

CREATE INDEX idx_change_asset ON asset_change (asset_id);
CREATE INDEX idx_change_status ON asset_change (status);

-- Audit trail: who acted at each step, what they did and when.
CREATE TABLE asset_change_step (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id     BIGINT      NOT NULL REFERENCES asset_change (id),
    step_order    INT         NOT NULL,
    approver_role VARCHAR(32) NOT NULL,
    decision      VARCHAR(16) NOT NULL,
    decided_by    VARCHAR(80),
    comment       VARCHAR(1000),
    decided_at    TIMESTAMP
);

CREATE INDEX idx_change_step ON asset_change_step (change_id);
